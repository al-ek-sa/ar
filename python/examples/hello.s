; Программа выводит "Hello, World!" и перевод строки через порт вывода.
; Строка лежит в памяти данных как C-строка (cstr): символы по одному
; байту и завершающий ноль. Процедура print_str выводит её посимвольно,
; пока не встретит ноль.

.equ OUT_PORT, 0x84                 ; адрес порта вывода в памяти данных (MMIO)

.data
msg:    .byte "Hello, World!", 0  ; строка с переводом строки и завершающим нулём
                                    ; первая буква на 0х100

.text
.org 0x00                           ; адрес начала работы
    j    _start                     ; переход к началу программы

.global _start
_start:
    li   a0, msg                    ; a0 = 0x100, адрес строки, аргумент print_str
    jal  print_str                  ; вызов процедуры, адрес возврата в ra
    halt                            ; остановка процессора

; print_str: выводит C-строку в порт вывода
;   вход:   a0 = адрес строки
;   портит: a0, t0, t1
print_str:
    li   t1, OUT_PORT               ; t1 = 0x84, адрес порта вывода
print_loop:
    lbu  t0, 0(a0)                  ; t0 = символ по адресу a0
    beqz t0, print_end              ; проверка нулевого байта
    sw   t0, 0(t1)                  ; запись в порт
    addi a0, a0, 1                  ; a0 указывает на следующий символ
    j    print_loop                 ; повтор цикла, пока не встретится нулевой байт

; возврат с цикла

print_end:
    ret                             ; возврат по адресу из ra, к halt в _start
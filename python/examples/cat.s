; Программа выводит все символы, поданные на ввод.
; Ввод работает через прерывания: каждый символ из расписания ввода
; вызывает прерывание, обработчик читает символ из порта ввода и сразу
; пишет его в порт вывода. Нулевой символ означает конец ввода.

.equ IN_PORT,   0x80                ; адрес порта ввода (MMIO)
.equ OUT_PORT,  0x84                ; адрес порта вывода (MMIO)
.equ STACK_TOP, 0x1000              ; начальная вершина стека, стек растёт вниз

.text
.org 0x00                           ; вектор сброса
    j    _start
.org 0x04                           ; вектор прерывания
    j    isr                        ; переходит при каждом прерывании

.global _start
_start:
    li   sp, STACK_TOP              ; стек настраивается до разрешения прерываний
    ei                              ; разрешить прерывания
idle:
    j    idle                       ; ждать прерываний

; isr: обработчик прерывания ввода

isr:
    addi sp, sp, -4                 ; выделить место на стеке
    sw   t0, 0(sp)                  ; сохранить t0 прерванной программы
    lw   t0, IN_PORT(zero)          ; прочитать символ из порта ввода
    beqz t0, stop                   ; если введен ноль, то ввод окончен
    sw   t0, OUT_PORT(zero)         ; вывести символ
    lw   t0, 0(sp)                  ; восстановить t0
    addi sp, sp, 4                  ; освободить место на стеке
    iret                            ; pc = epc прерывания разрешены
stop:
    halt                            ; остановка
